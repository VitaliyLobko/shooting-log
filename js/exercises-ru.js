const tr = (s) => (typeof s === 'string' ? PAIRS.get(s.trim()) ?? s : s);

/** Запис вправи з перекладеними рядками; нічого не збіглося — той самий об’єкт. */
export function translateExercise(rec) {
  const out = {
    ...rec,
    name: tr(rec.name),
    rules: typeof rec.rules === 'string' ? rec.rules.split('\n').map((line) => { const to = tr(line); return to === line ? line : to; }).join('\n') : rec.rules,
    ...(rec.zones ? { zones: rec.zones.map((z) => ({ ...z, label: tr(z.label) })) } : {}),
    ...(rec.variants ? { variants: rec.variants.map((x) => ({ ...x, label: tr(x.label) })) } : {}),
    ...(Array.isArray(rec.ranks) ? { ranks: rec.ranks.map(([min, name]) => [min, tr(name)]) } : {}),
  };
  return JSON.stringify(out) === JSON.stringify(rec) ? rec : out;
}
