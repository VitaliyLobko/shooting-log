const G = 9.80665;
const DT = 0.0005;

/** Щільність повітря — частка стандартної (+15 °C, рівень моря): барометрична формула ICAO, без вологості. */
export const airRatio = (tC, alt) => Math.pow(1 - 2.25577e-5 * alt, 5.25588) * 288.15 / (273.15 + tC);

/** Монотонний кубічний сплайн (PCHIP), як pchip_eval у py-ballisticcalc. */
function pchip(xs, ys) {
  const n = xs.length; const h = []; const s = [];
  for (let i = 0; i < n - 1; i++) { h.push(xs[i + 1] - xs[i]); s.push((ys[i + 1] - ys[i]) / h[i]); }
  const d = new Array(n).fill(0);
  for (let i = 1; i < n - 1; i++) {
    if (s[i - 1] * s[i] > 0) {
      const w1 = 2 * h[i] + h[i - 1]; const w2 = h[i] + 2 * h[i - 1];
      d[i] = (w1 + w2) / (w1 / s[i - 1] + w2 / s[i]);
    }
  }
  const end = (h0, h1, s0, s1) => {
    let v = ((2 * h0 + h1) * s0 - h0 * s1) / (h0 + h1);
    if (Math.sign(v) !== Math.sign(s0)) v = 0;
    else if (Math.sign(s0) !== Math.sign(s1) && Math.abs(v) > Math.abs(3 * s0)) v = 3 * s0;
    return v;
  };
  if (n > 2) { d[0] = end(h[0], h[1], s[0], s[1]); d[n - 1] = end(h[n - 2], h[n - 3], s[n - 2], s[n - 3]); }
  return (x) => {
    if (x <= xs[0]) return ys[0];
    if (x >= xs[n - 1]) return ys[n - 1];
    let lo = 0; let hi = n - 1;
    while (hi - lo > 1) { const m = (lo + hi) >> 1; if (xs[m] > x) hi = m; else lo = m; }
    const t = (x - xs[lo]) / h[lo]; const t2 = t * t; const t3 = t2 * t;
    return (2 * t3 - 3 * t2 + 1) * ys[lo] + (t3 - 2 * t2 + t) * h[lo] * d[lo] + (-2 * t3 + 3 * t2) * ys[lo + 1] + (t3 - t2) * h[lo] * d[hi];
  };
}

const curves = {};
const cdOf = (model) => (curves[model] ??= pchip(...DRAG[model]));

/**
 * Політ до дистанції max: кут ствола angle (рад), бічний вітер wind (м/с). Повертає точки на кожних step метрах:
 * { x, y, z, t, v } — y від осі ствола біля дула, z — знесення вітром.
 */
function fly({ k0, cd, c, mv, angle, wind, max, step }) {
  let x = 0; let y = 0; let z = 0; let vx = mv * Math.cos(angle); let vy = mv * Math.sin(angle); let vz = 0; let tm = 0;
  const acc = (ax, ay, az) => {
    const rz = az - wind; const v = Math.hypot(ax, ay, rz); const k = k0 * cd(v / c) * v;
    return [-k * ax, -k * ay - G, -k * rz];
  };
  const out = []; let next = step;
  while (x < max + 1e-9) {
    const a1 = acc(vx, vy, vz);
    const b = [vx + a1[0] * DT / 2, vy + a1[1] * DT / 2, vz + a1[2] * DT / 2]; const a2 = acc(...b);
    const c3 = [vx + a2[0] * DT / 2, vy + a2[1] * DT / 2, vz + a2[2] * DT / 2]; const a3 = acc(...c3);
    const e = [vx + a3[0] * DT, vy + a3[1] * DT, vz + a3[2] * DT]; const a4 = acc(...e);
    const p = { x, y, z, t: tm, v: Math.hypot(vx, vy, vz) };
    x += (vx + 2 * b[0] + 2 * c3[0] + e[0]) * DT / 6;
    y += (vy + 2 * b[1] + 2 * c3[1] + e[1]) * DT / 6;
    z += (vz + 2 * b[2] + 2 * c3[2] + e[2]) * DT / 6;
    vx += (a1[0] + 2 * a2[0] + 2 * a3[0] + a4[0]) * DT / 6;
    vy += (a1[1] + 2 * a2[1] + 2 * a3[1] + a4[1]) * DT / 6;
    vz += (a1[2] + 2 * a2[2] + 2 * a3[2] + a4[2]) * DT / 6;
    tm += DT;
    if (vx < 50) break;
    while (x >= next && next <= max + 1e-9) {
      const q = (next - p.x) / (x - p.x); const v = Math.hypot(vx, vy, vz);
      out.push({ x: next, y: p.y + (y - p.y) * q, z: p.z + (z - p.z) * q, t: p.t + DT * q, v: p.v + (v - p.v) * q });
      next += step;
    }
  }
  return out;
}

/**
 * Таблиця для тренажера: поправки H (MRAD, додатне — винос угору) і знесення W (MRAD на 1 м/с бічного вітру),
 * час польоту T (с) і швидкість V (м/с) на step, 2·step … max м. bc — у фунтах на кв. дюйм, як на коробці;
 * sh — висота прицілу над віссю ствола, см; пристрілка zero — точка, де лінія прицілу перетинає траєкторію вдруге.
 */
export function solve({ bc, model = 'G7', mv, sh = 6, zero = 100, tC = 15, alt = 0, max = 700, step = 50 }) {
  if (!(bc > 0 && mv > 0 && DRAG[model])) return null;
  const base = { k0: (airRatio(tC, alt) * 2.08551e-4) / bc / 0.3048, cd: cdOf(model), c: 20.0467 * Math.sqrt(273.15 + tC), mv, max, step };
  const los = sh / 100;
  let angle = 0;
  for (let i = 0; i < 8; i++) {
    const pt = fly({ ...base, angle, wind: 0, max: zero, step: zero })[0];
    if (!pt) return null;
    const miss = pt.y - los;
    angle -= Math.atan(miss / zero);
    if (Math.abs(miss) < 1e-5) break;
  }
  const still = fly({ ...base, angle, wind: 0 }); const windy = fly({ ...base, angle, wind: 1 });
  if (still.length < max / step) return null;
  return {
    H: still.map((p) => -1000 * Math.atan((p.y - los) / p.x)),
    W: windy.map((p) => 1000 * Math.atan(p.z / p.x)),
    T: still.map((p) => p.t),
    V: still.map((p) => p.v),
  };
}
