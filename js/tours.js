// Розмітка мішені: редактор фото (target.js) і вирівнювання перед ним (align.js). Самі — при першому відкритті.
const once = (key) => { try { if (localStorage.getItem(key) === '1') return false; localStorage.setItem(key, '1'); } catch { /* приватний режим */ } return true; };
const pick = (sel) => () => document.querySelector(sel)?.click();

/** Тур вирівнювання: кути рамки на кути листа, розмір листа, далі — дані й розмітка. */
export function alignTour({ auto = false } = {}) {
  if (auto && !once('shooters-log:align-tour')) return Promise.resolve(false);
  return runTour([
    { sel: ['.align-stage'], title: 'Шаг 1 из 3 — выровнять', text: 'Мишень сфотографирована под углом? Перетащите четыре угла рамки на углы листа — фото выпрямится, и пробоины лягут на свои места.' },
    { sel: ['.align-crop', '.align-sheet'], title: 'Размер листа', text: 'Знаете формат листа (A4, IPSC…) — выберите его: масштаб для размеров задастся сам. Не знаете — снимите «Обрезать по рамке» и поставьте рамку на любой квадрат сетки.' },
    { sel: ['.align .viewer-actions'], title: 'Дальше', text: '«Готово» — к данным выстрела: оружие, прицел, дистанция. Фото ровное — «Пропустить». Потом — разметка пробоин.' },
  ]);
}

